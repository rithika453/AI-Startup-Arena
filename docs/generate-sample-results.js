'use strict';
// Regenerates docs/SAMPLE_RESULTS.md from the live pipeline: node docs/generate-sample-results.js
const fs = require('node:fs');
const path = require('node:path');
const { runTeamMatching } = require('../src');
const ideas = [
  ['Technical startup (AI SaaS)', 'An AI-powered SaaS platform that automates customer support using LLM chatbots for e-commerce businesses'],
  ['Physical-product startup', 'A smart reusable water bottle that tracks hydration, manufactured and sold to fitness consumers'],
  ['Service-based business', 'A digital marketing agency helping small local restaurants grow with social media management and SEO services'],
  ['Agriculture marketplace', 'A marketplace connecting farmers directly with buyers to sell fresh produce, with delivery logistics'],
  ['HealthTech mobile app (shows a missing role)', 'A mobile app for telemedicine consultations between rural patients and doctors'],
];
let md = '# Sample results (generated)\n\nGenerated by `node docs/generate-sample-results.js` from the rule-based pipeline using DEMO candidate profiles (fictional). Scores are heuristics, not guarantees.\n';
for (const [label, idea] of ideas) {
  const r = runTeamMatching({ idea });
  md += `\n## ${label}\n\n> ${idea}\n\n- Domain: **${r.domainAnalysis.primary.name}**${r.domainAnalysis.subdomain ? ` / ${r.domainAnalysis.subdomain.name}` : ''} (confidence ${Math.round(r.domainAnalysis.confidence * 100)}%)\n- Business type: **${r.businessModel.label}**\n\n| Role | Priority | Top candidate(s) (score /100) |\n|---|---|---|\n`;
  for (const role of r.matching.byRole) {
    const cands = role.candidates.length ? role.candidates.map((c) => `${c.name} (${c.score})`).join(', ') : '**no suitable candidate**';
    md += `| ${role.title} | ${role.priority} | ${cands} |\n`;
  }
  md += r.missingRoles.length ? `\nMissing roles: ${r.missingRoles.map((m) => m.title).join('; ')}\n` : '\nMissing roles: none\n';
}
fs.writeFileSync(path.join(__dirname, 'SAMPLE_RESULTS.md'), md);
console.log('wrote docs/SAMPLE_RESULTS.md');
